	assert PHONE_EVENT_RESULT_REMATCH == 1
	assert PHONE_EVENT_RESULT_FLAVOR == PHONE_EVENT_FLAVOR
	assert PHONE_EVENT_RESULT_TRIVIA == NUM_PHONE_EVENTS
	assert PHONE_EVENT_RESULT_FAMILY == 10
	assert NUM_PHONE_EVENT_RESULTS <= $100
	assert PHONE_EVENT_ROLL_WHEN_DISABLED == $80
	assert PHONE_EVENT_CAPABILITY_FLAG_MASK == PHONE_EVENT_ROLL_WHEN_DISABLED
	assert PHONE_EVENT_ROLL_WHEN_DISABLED >= NUM_PHONE_EVENTS
	assert PHONE_EVENT_FLAVOR & PHONE_EVENT_CAPABILITY_FLAG_MASK == 0
