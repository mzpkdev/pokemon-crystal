; Entry-local policy flag stored in the capability byte. A disabled nonterminal
; entry with this flag still consumes and discards its configured random roll.
DEF PHONE_EVENT_ROLL_WHEN_DISABLED EQU 1 << 7
DEF PHONE_EVENT_CAPABILITY_FLAG_MASK EQU PHONE_EVENT_ROLL_WHEN_DISABLED
; Transient selector input flag. This shares the staged candidate byte but is
; stripped before capability gating; it is never stored in SRAM.
DEF PHONE_EVENT_USE_REPEAT_POLICY EQU 1 << 7
DEF PHONE_EVENT_CAP_MASK EQU (1 << NUM_PHONE_EVENT_CAPABILITIES) - 1
